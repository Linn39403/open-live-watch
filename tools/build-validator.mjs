import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
const schema = JSON.parse(
  readFileSync(
    new URL("../schemas/workspace.schema.json", import.meta.url),
    "utf8",
  ),
);
const ajv = new Ajv2020({
  allErrors: true,
  code: { source: true, esm: true, lines: true },
});
let output = standaloneCode(ajv, ajv.compile(schema));
const imports = [];
output = output.replace(/require\("([^\"]+)"\)\.default/g, (_, path) => {
  const name = "runtime" + imports.length;
  imports.push(
    `import ${name}Import from ${JSON.stringify(path + ".js")};\nconst ${name}=typeof ${name}Import==='function'?${name}Import:${name}Import.default;`,
  );
  return name;
});
writeFileSync(
  new URL("../src/workspace-validator.js", import.meta.url),
  "// Generated by tools/build-validator.mjs; do not edit.\n" +
    imports.join("\n") +
    "\n" +
    output,
);
